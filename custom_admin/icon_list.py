def get_icon_choices():
    """Return icon choices as tuple list for Django forms"""
    return [(icon[0], icon[1]) for icon in ICONSAX_ICONS]

def get_icon_name(icon_code):
    """Get display name for an icon code"""
    for icon in ICONSAX_ICONS:
        if icon[0] == icon_code:
            return icon[1]
    return icon_code

